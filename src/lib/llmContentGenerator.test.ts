import { describe, it, expect, vi, beforeEach } from 'vitest';
import { getCharacterLimit } from './contentLengthLimits';

// Mock the API functions and other dependencies
vi.mock('./contentLengthLimits', () => ({
  getCharacterLimit: vi.fn(),
}));

// Import the module after mocking dependencies
import * as llmContentGenerator from './llmContentGenerator';

// Mock the environment variables
vi.stubEnv('MISTRAL_API_KEY', 'test-mistral-key');
vi.stubEnv('DEEPSEEK_API_KEY', 'test-deepseek-key');
vi.stubEnv('GROQ_API_KEY', 'test-groq-key');
vi.stubEnv('HUGGINGFACE_API_KEY', 'test-huggingface-key');

// Mock fetch
global.fetch = vi.fn();

describe('llmContentGenerator', () => {
  beforeEach(() => {
    vi.resetAllMocks();
    vi.mocked(getCharacterLimit).mockReturnValue(1000);
    
    // Reset fetch mock
    vi.mocked(global.fetch).mockReset();
  });

  describe('generateAIPost', () => {
    it('should generate a post with the correct structure', async () => {
      // Mock successful API response
      vi.mocked(global.fetch).mockResolvedValueOnce({
        ok: true,
        json: vi.fn().mockResolvedValue({
          choices: [
            {
              message: {
                content: 'This is a test content generated by the API.'
              }
            }
          ]
        })
      } as any);

      const brandInfo = {
        brandName: 'Test Brand',
        businessDescription: 'A test business',
        targetAudience: 'Test audience',
        contentThemes: ['theme1', 'theme2'],
        tone: 'professional',
        specialDays: '',
        ctaExamples: '',
        contentLength: 'full' as const
      };

      const post = await llmContentGenerator.generateAIPost(
        'Jun 01, 2025',
        'twitter',
        'theme1',
        brandInfo
      );

      // Check post structure
      expect(post).toHaveProperty('id');
      expect(post).toHaveProperty('date', 'Jun 01, 2025');
      expect(post).toHaveProperty('platform', 'twitter');
      expect(post).toHaveProperty('content');
      expect(post).toHaveProperty('hashtags');
      expect(Array.isArray(post.hashtags)).toBe(true);
    });

    it('should handle API errors gracefully', async () => {
      // Mock failed API responses for all providers
      vi.mocked(global.fetch).mockRejectedValue(new Error('API error'));

      const brandInfo = {
        brandName: 'Test Brand',
        businessDescription: 'A test business',
        targetAudience: 'Test audience',
        contentThemes: ['theme1', 'theme2'],
        tone: 'professional',
        specialDays: '',
        ctaExamples: '',
        contentLength: 'full' as const
      };

      // The function should not throw but return mock content
      const post = await llmContentGenerator.generateAIPost(
        'Jun 01, 2025',
        'twitter',
        'theme1',
        brandInfo
      );

      expect(post).toHaveProperty('content');
      expect(post.content.length).toBeGreaterThan(0);
    });
  });

  describe('generateAIContentPlan', () => {
    it('should generate a content plan with posts for multiple platforms', async () => {
      // Mock successful API response
      vi.mocked(global.fetch).mockResolvedValue({
        ok: true,
        json: vi.fn().mockResolvedValue({
          choices: [
            {
              message: {
                content: 'This is a test content generated by the API.'
              }
            }
          ]
        })
      } as any);

      const brandInfo = {
        brandName: 'Test Brand',
        businessDescription: 'A test business',
        targetAudience: 'Test audience',
        contentThemes: ['theme1', 'theme2'],
        tone: 'professional',
        specialDays: '',
        ctaExamples: '',
        contentLength: 'full' as const
      };

      const contentPlan = await llmContentGenerator.generateAIContentPlan(brandInfo);

      // Check content plan structure
      expect(Array.isArray(contentPlan)).toBe(true);
      expect(contentPlan.length).toBeGreaterThan(0);
      
      // Check that we have posts for different platforms
      const platforms = new Set(contentPlan.map(post => post.platform));
      expect(platforms.size).toBeGreaterThan(1);
      
      // Check that each post has the required properties
      contentPlan.forEach(post => {
        expect(post).toHaveProperty('id');
        expect(post).toHaveProperty('date');
        expect(post).toHaveProperty('platform');
        expect(post).toHaveProperty('content');
        expect(post).toHaveProperty('hashtags');
      });
    });
  });

  // Test character limit enforcement
  describe('character limit enforcement', () => {
    it('should respect character limits for different platforms', async () => {
      // Mock getCharacterLimit to return different values for different platforms
      vi.mocked(getCharacterLimit)
        .mockImplementation((platform, contentLength) => {
          if (platform === 'twitter') return 280;
          if (platform === 'linkedin') return 1248;
          if (platform === 'facebook') return 2000;
          return 1000;
        });

      // Mock successful API response with long content
      const longContent = 'a'.repeat(3000); // Content longer than any platform limit
      vi.mocked(global.fetch).mockResolvedValue({
        ok: true,
        json: vi.fn().mockResolvedValue({
          choices: [
            {
              message: {
                content: longContent
              }
            }
          ]
        })
      } as any);

      const brandInfo = {
        brandName: 'Test Brand',
        businessDescription: 'A test business',
        targetAudience: 'Test audience',
        contentThemes: ['theme1'],
        tone: 'professional',
        specialDays: '',
        ctaExamples: '',
        contentLength: 'full' as const
      };

      // Generate posts for different platforms
      const twitterPost = await llmContentGenerator.generateAIPost(
        'Jun 01, 2025',
        'twitter',
        'theme1',
        brandInfo
      );

      const linkedinPost = await llmContentGenerator.generateAIPost(
        'Jun 01, 2025',
        'linkedin',
        'theme1',
        brandInfo
      );

      const facebookPost = await llmContentGenerator.generateAIPost(
        'Jun 01, 2025',
        'facebook',
        'theme1',
        brandInfo
      );

      // Check that content length respects platform limits
      expect(twitterPost.content.length).toBeLessThanOrEqual(280);
      expect(linkedinPost.content.length).toBeLessThanOrEqual(1248);
      expect(facebookPost.content.length).toBeLessThanOrEqual(2000);
    });
  });
});
